namespace PPS.Solver
{
    /// <summary>
    /// 탐색이 멈춘 이유.
    /// "예산 안에 못 찾음" 과 "못 푸는 판" 이 같은 값으로 나가면
    /// 풀리는 레벨을 못 푼다고 판정하게 된다 — 프로젝트 실패 조건이다.
    /// 그래서 이 목록에 "불가능" 은 없다. 후보 격자 밖의 풀이는
    /// 이 탐색이 볼 수 없으므로 없다고 말할 자격이 없다.
    /// </summary>
    public enum SolverStop
    {
        /// <summary>
        /// 열린 목록이 비었다. 잉크 한도가 깊이를 묶으므로 여기까지 온다.
        /// 뜻은 "이 후보 격자와 잉크 한도 안에는 없다" 이지
        /// "이 레벨은 못 푼다" 가 아니다.
        /// 기본값을 여기 둔다 — 못 채운 보고서가 Solved 로 읽히면 안 된다.
        /// </summary>
        Exhausted = 0,

        /// 풀이를 찾았다. 이때만 Solution 이 채워진다.
        Solved,

        /// 시뮬 횟수 예산을 다 썼다.
        SimBudget,

        /// 시간 예산을 다 썼다.
        TimeBudget,
    }
}
